    /**
     *  Returns le total de vente par mois par mois
     */
    public function getOrderByMonth(): array
    {
        $sql = '
            SELECT MONTH(created_at) AS month, total_price AS total
            FROM ORDER
            GROUP BY month, total
            ORDER BY month ASC
        ';
        return $this->getEntityManager()->getConnection()
            ->executeQuery($sql)
            ->fetchAllAssociative();
    }

